-- Going public (docs/multi-band-plan.md, phase 4): owners invite people into their band, and every change
-- made through the API is written down.

-- An invitation into a band: for one e-mail address, as a role, valid until expires_at; the link carries a
-- random token, only its SHA-256 is kept. Accepted once (accepted_at), by a user signed in with that address.
create table invitation (
    id          uuid          not null primary key,
    band_id     uuid          not null references band (id) on delete cascade,
    email       varchar(320)  not null,
    role        varchar(20)   not null,
    token_hash  varchar(64)   not null unique,
    invited_by  uuid          references app_user (id) on delete set null,
    created_at  timestamp(6) with time zone not null,
    expires_at  timestamp(6) with time zone not null,
    accepted_at timestamp(6) with time zone,
    accepted_by uuid          references app_user (id) on delete set null
);
create index invitation_band on invitation (band_id);

-- Who changed what in a band, when: every change made through the API (its operation, what it named, how
-- it ended), kept with the band.
create table audit_event (
    id        bigint        generated by default as identity primary key,
    band_id   uuid          not null references band (id) on delete cascade,
    user_id   uuid          references app_user (id) on delete set null,
    action    varchar(100)  not null,
    target    varchar(300),
    status    integer       not null,
    at        timestamp(6) with time zone not null
);
create index audit_event_band_at on audit_event (band_id, at desc);
